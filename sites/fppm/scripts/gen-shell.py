#!/usr/bin/env python3
"""The theme around fppm.us's pages (WordPress 7.1.5's Twenty Twenty-Five, a
block theme, with the site's own header, footer, navigation and styles), cut
from pages rendered by a local copy of the site — real WordPress on Martin's
database export with the real plugins (test/wp-real.sh) — and written to
src/render/shell.gen.ts, with the list of local files they load.

    python3 -I scripts/gen-shell.py http://127.0.0.1:8099 src/render/shell.gen.ts

(fppm.us itself answered 502 for days in November 2026, so its pages could not
be fetched; the local copy renders the same theme, templates and settings.)

The local copy is asked with X-Test-Shell (test/wp-real/fppm-test-mu.php):
the plugin's shortcodes come back as markers, and so do its wp_head and
wp_footer output, so the frame is everything else. The Worker fills:
  __SC_<shortcode>__  the shortcode's output (after WordPress's template-level
                      wptexturize, convert_smilies and wp_filter_content_tags,
                      as src/render/texturize.ts does)
  __FPPM_HEAD__ / __FPPM_FOOTER__  the plugin's head tags and install pill
  __LOGGED_IN__       " logged-in" in the body class when someone is signed in
Left out: feed, oEmbed, REST and RSD links, the generator tag, the shortlink
(WordPress endpoints the Worker does not have), and Nextend Social Login's
scripts (its popup sign-in; the Google button now goes to the shared accounts
sign-in). Kept: Nextend's button styles. The admin bar is not drawn (no
wp-admin).
"""
import json
import re
import sys
import urllib.request

base, out_path = sys.argv[1], sys.argv[2]
# key: (path, signed-in user for the render; 0 = signed out)
PAGES = {"home": ("/", 0), "go": ("/go/", 0), "account": ("/account/", 1), "roster": ("/roster/", 1), "notfound": ("/no-such-page-here/", 1)}

DROP = [
    r"<link rel='dns-prefetch' href='//fppm\.us' />\n?",
    r'<link rel="alternate"[^>]*/>\n?',
    r'<link rel="https://api\.w\.org/"[^>]*/>\n?', r'<link rel="EditURI"[^>]*/>\n?', r"<link rel='shortlink'[^>]*/>\n?",
    r'<meta name="generator"[^>]*/>\n?',
    r'<script type="text/javascript">\s*window\._nslDOMReady.*?</script>\n?',
    r'<script type="text/javascript">\(function \(undefined\) \{let scriptOptions=.*?</script>',
]


def fetch(path: str, uid: int) -> tuple[int, str]:
    req = urllib.request.Request(base + path, headers={"Host": "fppm.us", "X-Test-Shell": "1", "X-Test-User": str(uid)})
    try:
        with urllib.request.urlopen(req) as r:
            return r.status, r.read().decode("utf-8")
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8")


out = {}
for key, (path, uid) in PAGES.items():
    status, h = fetch(path, uid)
    if (status == 404) != (key == "notfound") or status not in (200, 404):
        raise SystemExit(f"{path}: HTTP {status}")
    for p in DROP:
        h = re.sub(p, "", h, flags=re.S)
    if "nsl" in h.lower() and re.search(r"<script[^>]*>[^<]*nsl", h, flags=re.I):
        raise SystemExit(f"{path}: a Nextend script is left")
    h = h.replace("<!--FPPM_HEAD-->", "__FPPM_HEAD__").replace("<!--FPPM_FOOTER-->", "__FPPM_FOOTER__")
    h = re.sub(r"<!--FPPM_SC:(fppm_[a-z_]+)-->", r"__SC_\1__", h)
    h = re.sub(r'(<body class="[^"]*?)( logged-in)?( wp-custom-logo)', r"\1__LOGGED_IN__\3", h, count=1)
    if "__LOGGED_IN__" not in h or "__FPPM_HEAD__" not in h or "__FPPM_FOOTER__" not in h:
        raise SystemExit(f"{path}: a marker is missing")
    out[key] = h

files = sorted(set(re.findall(r"https://fppm\.us(/(?:wp-content|wp-includes)/[^\"')\s?#]+)", "".join(out.values()))))
with open(out_path, "w", encoding="utf-8") as f:
    f.write("/* Generated by scripts/gen-shell.py from a local render of fppm.us (WordPress 7.1.5, Twenty Twenty-Five). Do not edit. */\n")
    f.write(f"export const SHELLS: Record<string, string> = {json.dumps(out, ensure_ascii=False)};\n")
    f.write(f"export const FILES: string[] = {json.dumps(files)};\n")
for k, v in out.items():
    print(f"{k:9} {len(v):7d}  shortcodes: {re.findall(r'__SC_(fppm_[a-z_]+)__', v)}")
print(len(files), "local files")
