#!/usr/bin/env python3
"""The plugin's fixed markup, cut from fppm-team-manager.php itself into
src/fppm/templates.gen.ts, so the port prints the same bytes without anyone
retyping them.

    python3 -I scripts/gen-templates.py [plugin.php] > src/fppm/templates.gen.ts

For each function listed in FUNCS, the HTML between its `?>` and `<?php`
tags becomes a list of literal chunks (PHP swallows one newline right after
`?>`, so the chunks do too); the port prints chunk[0], then what the first
PHP hole printed, then chunk[1], and so on. `--holes` prints each function's
PHP holes in order instead (for writing the port).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = ROOT / "../../imports/siteground/fppm.us/wp-content/plugins/fppm-team-manager/fppm-team-manager.php"
FUNCS = ["fppm_styles", "fppm_sc_register", "fppm_complete_form", "fppm_install_card", "fppm_settings_page",
         "fppm_waivers_page", "fppm_store_html", "fppm_pwa_serve", "fppm_pwa_footer"]


def body_of(src: str, name: str) -> str:
    m = re.search(r"^function " + name + r"\s*\(.*?\)\s*\{\n", src, re.M)
    if not m:
        raise SystemExit(f"no function {name}")
    # The function ends at the first line that is exactly "}" after it.
    end = src.index("\n}\n", m.end())
    return src[m.end():end + 1]


def split(body: str):
    """Literal chunks and the PHP holes between them, in order."""
    chunks, holes = [], []
    i = body.index("?>")
    while True:
        lit_start = i + 2
        if body.startswith("\r\n", lit_start):
            lit_start += 2
        elif body.startswith("\n", lit_start):
            lit_start += 1
        j = body.find("<?php", lit_start)
        if j < 0:
            break
        chunks.append(body[lit_start:j])
        k = body.find("?>", j)
        if k < 0:
            break
        holes.append(body[j + 5:k].strip())
        i = k
    return chunks, holes


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    src = Path(args[0] if args else DEFAULT).read_text(encoding="utf-8")
    ver = re.search(r"Version:\s*(\S+)", src).group(1)
    if "--holes" in sys.argv:
        for f in FUNCS:
            chunks, holes = split(body_of(src, f))
            print(f"== {f}: {len(chunks)} chunks")
            for n, h in enumerate(holes):
                print(f"  [{n}] {h}")
        dbk = DEFAULT.parent.parent / "gff-drive-backup/gff-drive-backup.php"
        chunks, holes = split(body_of(dbk.read_text(encoding="utf-8"), "gff_dbk_settings_page"))
        print(f"== gff_dbk_settings_page: {len(chunks)} chunks")
        for n, h in enumerate(holes):
            print(f"  [{n}] {h}")
        return
    print(f"/* Generated by scripts/gen-templates.py from fppm-team-manager.php {ver}. Do not edit. */")
    for f in FUNCS:
        chunks, _ = split(body_of(src, f))
        print(f"export const {f.upper()}: string[] = {json.dumps(chunks, ensure_ascii=False)};")
    # GFF Drive Backup's settings page (the plugin is byte-identical to the farm's copy).
    dbk = (Path(args[0]).parent.parent if args else DEFAULT.parent.parent) / "gff-drive-backup/gff-drive-backup.php"
    chunks, _ = split(body_of(dbk.read_text(encoding="utf-8"), "gff_dbk_settings_page"))
    print(f"export const GFF_DBK_SETTINGS_PAGE: string[] = {json.dumps(chunks, ensure_ascii=False)};")
    # The built-in waiver template's lines (fppm_waiver_text()), as the PHP double-quoted strings hold them.
    w = body_of(src, "fppm_waiver_text")
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', w[w.index("return \"WAIVER"):])
    print(f"export const WAIVER_PARTS: string[] = {json.dumps([bytes(p, 'utf-8').decode('unicode_escape').encode('latin-1').decode('utf-8') for p in parts], ensure_ascii=False)};")


if __name__ == "__main__":
    main()
