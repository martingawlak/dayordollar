<?php
/**
 * The plugin's fixed markup, captured from the plugin itself and written to
 * src/render/templates.gen.ts. Each piece is rendered by the plugin with
 * sentinel values (@@NAME@@) where its few variable parts go — a shortcode
 * attribute, a notice, a repopulated field — so the Worker's port fills the
 * same holes with the same escaped values. Each is rendered signed out and
 * signed in as two different people; if those differ, or a hole is not found
 * exactly once, this script stops. Re-run when the plugin changes:
 *   php scripts/gen-templates.php     (needs the gff_fixture database, test/fixture.sh)
 */
$GLOBALS['NOW'] = time();
require __DIR__ . '/../test/wp.php';
load_plugin();

/*
 * const => [setup PHP, expression, [literal => replacement | [replacement, times]], [holes that must appear once], slice-from marker]
 * The setup runs in the request before the expression (e.g. filling $gff_reg_state).
 * A slice-from marker keeps only the output from that marker on (a function's fixed tail).
 */
$S = '$GLOBALS["gff_reg_state"]';
$FNS = [
	// Site-wide assets (gff_reg_register_assets).
	'REG_CSS'        => ['', 'gff_reg_css()', [], []],
	'FONT_CSS'       => ['', 'gff_reg_font_overrides()', [], []],
	'VALIDATION_JS'  => ['', 'gff_reg_validation_js()', [], []],
	// The home page's shortcodes.
	'ZORA_DISPLAY_T' => ['', 'gff_sc_zora_display()', [], []],
	'EXPRESS_START_T' => ["{$S}['notice'] = '@@NOTICE@@';", 'gff_sc_express_start()', [], ['NOTICE']],
	'EXPRESS_EMAIL_T' => ["{$S}['repop'] = true; {$S}['old']['gff_express_email'] = '@@EMAIL@@';",
		"gff_sc_express_email(['legend' => '@@LEGEND@@', 'label' => '@@LABEL@@'])", [' value="@@EMAIL@@"' => '@@VAL@@'], ['VAL', 'LEGEND', 'LABEL']],
	'CONSULT_T'      => ['', "gff_sc_consult(['legend' => '@@LEGEND@@'])", [], ['LEGEND']],
	'THREE_SISTERS_T' => ['', 'gff_reg_three_sisters_field(true)', [], []],
	'AGREEMENT_T'    => ["{$S}['repop'] = true; {$S}['old']['gff_agree'] = 'yes';", 'gff_sc_agreement()',
		['name="gff_agree" value="yes" checked required>' => 'name="gff_agree" value="yes"@@CHECKED@@ required>', '@THREE_SISTERS@' => '@@THREE_SISTERS@@'], ['CHECKED', 'THREE_SISTERS']],
	'EXPRESS_SUBMIT_T' => ['', "gff_sc_express_submit(['label' => '@@LABEL@@'])", [], ['LABEL']],
	'FORM_END_T'     => ["{$S}['form_open'] = true; {$S}['notice'] = '@@NOTICE@@';", 'gff_sc_form_end()', [], ['NOTICE']],
	'CONVINCE_T'     => ['', "gff_sc_convince(['label' => '@@LABEL@@', 'open' => 'yes'])", ['<details class="gff-convince" open>' => '<details class="gff-convince"@@OPEN@@>'], ['LABEL', 'OPEN']],
	// The account page.
	'ACCT_STYLES'    => ['', 'gff_acct_styles()', [], []],
	'MY_FARM_STYLE'  => ['', 'gff_sc_my_farm()', [], [], "\t<style>", [1, 4, 29]], // signed in only
	// [gff_farm_builder]: its per-render id suffix (md5 of the test's uniqid), the mode, the saved layout.
	'FARM_BUILDER_T' => ['', "gff_sc_farm_builder(['mode' => '@@MODE@@'])",
		['fb' . substr(md5('uniq-1'), 0, 6) => ['@@SFX@@', 4], 'data-mode="@@MODE@@" hidden>' => 'data-mode="@@MODE@@"@@INIT@@ hidden>'], ['MODE', 'INIT']],
	// [gff_start]: the one-checkbox consent start.
	'START_T'        => ['', "gff_sc_start(['label' => '@@LABEL@@', 'note' => '@@NOTE@@', 'offer' => 'spire'])", ['data-offer="spire"' => 'data-offer="@@OFFER@@"'], ['LABEL', 'NOTE', 'OFFER']],
];
$out = [];
foreach ($FNS as $const => $spec) {
	[$setup, $expr, $repl, $holes] = $spec;
	$from = $spec[4] ?? null;
	$uids = $spec[5] ?? [0, 1, 4];
	$seen = [];
	foreach ($uids as $uid) {
		// Run in a child so the plugin's statics and globals start fresh.
		// The request path is a hole too: wp_nonce_field() prints it as the referer.
		$code = 'require ' . var_export(__DIR__ . '/../test/wp.php', true) . '; $GLOBALS["NOW"] = time(); $GLOBALS["UID"] = ' . $uid . '; $_SERVER["REQUEST_URI"] = "/@@REFERER@@"; load_plugin(); '
			. $setup . ' ob_start(); $r = ' . $expr . '; echo json_encode(ob_get_clean() . $r);';
		$seen[$uid] = json_decode(shell_exec('php -r ' . escapeshellarg($code)), true);
		if ($from !== null) { $at = strpos((string) $seen[$uid], $from); $seen[$uid] = $at === false ? '' : substr($seen[$uid], $at); }
	}
	if (count(array_unique($seen)) !== 1) { fwrite(STDERR, "$const varies by visitor\n"); exit(1); }
	$s = reset($seen);
	if (!is_string($s) || $s === '') { fwrite(STDERR, "$const printed nothing\n"); exit(1); }
	foreach ($repl as $find => $to) {
		if ($find === '@THREE_SISTERS@') $find = $out['THREE_SISTERS_T'];
		[$to, $times] = is_array($to) ? $to : [$to, 1];
		if ($times !== substr_count($s, $find)) { fwrite(STDERR, "$const: '$to' target found " . substr_count($s, $find) . " times, not $times\n"); exit(1); }
		$s = str_replace($find, $to, $s);
	}
	$s = str_replace('/@@REFERER@@', '@@REFERER@@', $s);
	foreach ($holes as $h) {
		if (1 !== substr_count($s, "@@$h@@")) { fwrite(STDERR, "$const: hole $h found " . substr_count($s, "@@$h@@") . " times\n"); exit(1); }
	}
	$out[$const] = $s;
}
$ts = "/* Generated by scripts/gen-templates.php from gff-customer-registration.php " . gff_plugin_version() . ". Do not edit. */\n";
foreach ($out as $k => $v) $ts .= "export const $k = " . json_encode($v, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . ";\n";
file_put_contents(__DIR__ . '/../src/render/templates.gen.ts', $ts);
foreach ($out as $k => $v) printf("%-18s %6d bytes\n", $k, strlen($v));

function gff_plugin_version(): string {
	preg_match('/^\s*\*\s*Version:\s*(\S+)/m', file_get_contents(PLUGIN_FILE), $m);
	return $m[1] ?? '?';
}
