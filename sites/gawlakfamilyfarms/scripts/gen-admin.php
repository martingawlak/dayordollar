<?php
/**
 * The client admin's fixed markup, from the plugin source itself: for each
 * template function (and the GFF Drive Backup plugin's settings page), every run of inline HTML between PHP tags, in source
 * order (PHP's own tokenizer, T_INLINE_HTML, which already applies the
 * "?> eats one newline" rule), and the two style blocks the dashboard
 * returns. Written to src/admin/chunks.gen.ts; the ports in src/admin/
 * interleave the pieces with the values the PHP echoed. Re-run when the
 * plugin changes:
 *   php scripts/gen-admin.php            (needs the gff_fixture database, test/fixture.sh)
 *   php scripts/gen-admin.php --dump FN  (prints one function's pieces, numbered)
 */
$GLOBALS['NOW'] = time();
require __DIR__ . '/../test/wp.php';
load_plugin();
$FNS = [
	'SETTINGS_T' => 'gff_reg_settings_page', 'PAY_FIELDS_T' => 'gff_reg_settings_pay_fields', 'MSG_RECIPIENT_T' => 'gff_reg_msg_recipient_field',
	'ADDON_FIELDS_T' => 'gff_reg_admin_addon_fields', 'ACCOUNT_FIELDS_T' => 'gff_reg_admin_account_fields', 'INVOICE_FIELDS_T' => 'gff_reg_admin_invoice_fields',
	'CLIENTS_T' => 'gff_reg_admin_page', 'DASH_INVOICE_T' => 'gff_dash_invoice_form', 'DASHBOARD_T' => 'gff_admin_dashboard',
	'ACTIVE_TOGGLE_T' => 'gff_active_toggle_form', 'NOTES_FORM_T' => 'gff_client_notes_form', 'LEAD_CONVERT_T' => 'gff_lead_convert_form',
	'DELETE_FORM_T' => 'gff_client_delete_form', 'CLASS_BTN_T' => 'gff_class_btn', 'ROUTE_TOGGLE_T' => 'gff_route_toggle_btn',
	'CLIENT_SECTION_T' => 'gff_dash_client_section', 'PLANTING_T' => 'gff_client_planting_html', 'GARDEN_BTN_T' => 'gff_garden_invite_btn',
	'PHONE_FIELD_T' => 'gff_dash_profile_phone_field', 'V33_PROFILE_T' => 'gff_v33_profile_ui',
	// The GFF Drive Backup plugin's settings page.
	'DBK_SETTINGS_T' => 'gff_dbk_settings_page',
];
$tokens = [];
$out = [];
foreach ($FNS as $const => $fn) {
	$rf = new ReflectionFunction($fn);
	$a = $rf->getStartLine(); $b = $rf->getEndLine();
	$file = $rf->getFileName(); // the loaded copy: same lines, same inline HTML as the plugin file
	$tokens[$file] ??= token_get_all(file_get_contents($file));
	$parts = [];
	foreach ($tokens[$file] as $t) if (is_array($t) && $t[0] === T_INLINE_HTML && $t[2] >= $a && $t[2] <= $b) $parts[] = $t[1];
	$out[$const] = $parts;
}
if (($argv[1] ?? '') === '--dump') {
	foreach ($out[$argv[2]] as $i => $p) echo "[$i] " . json_encode($p, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";
	exit;
}
$ts = "/* Generated by scripts/gen-admin.php from gff-customer-registration.php. Do not edit. */\n";
foreach ($out as $k => $v) $ts .= "export const $k: string[] = " . json_encode($v, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . ";\n";
$ts .= "export const ACCT_CSS = " . json_encode(gff_acct_styles(), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . ";\n";
$ts .= "export const DASH_CSS = " . json_encode(gff_admin_dash_styles(), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . ";\n";
file_put_contents(__DIR__ . '/../src/admin/chunks.gen.ts', $ts);
foreach ($out as $k => $v) printf("%-18s %3d pieces %6d bytes\n", $k, count($v), strlen(implode('', $v)));
