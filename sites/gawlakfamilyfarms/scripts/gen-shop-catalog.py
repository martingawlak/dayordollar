#!/usr/bin/env python3
"""The old WooCommerce shop's catalogue (products, variations, prices, images),
read from the site's WordPress database and written as a TypeScript module the
Worker sells from. Prices come only from here: the browser never sends one.
Public product data only (no orders, no customers).

    python3 -I scripts/gen-shop-catalog.py --db dod_old --prefix rjo_ --origin https://dayordollar.com --site dayordollar.com > src/shop/catalog.gen.ts
"""
import argparse, json, re, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from phpserialize import unserialize  # noqa: E402


def q(db, sql):
    out = subprocess.run(["mysql", "--default-character-set=utf8mb4", "--batch", "--raw", "-N", db, "-e", sql], check=True, capture_output=True, text=True).stdout
    return [json.loads(l) for l in out.splitlines() if l.strip()]


def main():
    ap = argparse.ArgumentParser()
    for a in ("--db", "--prefix", "--origin", "--site"): ap.add_argument(a, required=True)
    a = ap.parse_args(); p = a.prefix

    def meta(pid):
        return {r["k"]: r["v"] for r in q(a.db, f"select json_object('k', meta_key, 'v', meta_value) from {p}postmeta where post_id = {int(pid)}")}

    def image(att_id):
        if not att_id: return None
        f = q(a.db, f"select json_object('v', meta_value) from {p}postmeta where post_id = {int(att_id)} and meta_key = '_wp_attached_file'")
        return f"{a.origin}/wp-content/uploads/{f[0]['v']}" if f else None

    terms = {}
    for r in q(a.db, f"select json_object('tax', tt.taxonomy, 'slug', t.slug, 'name', t.name) from {p}terms t join {p}term_taxonomy tt on tt.term_id = t.term_id where tt.taxonomy like 'pa\\\\_%'"):
        terms[(r["tax"], r["slug"])] = r["name"]
    labels = {r["n"]: r["l"] for r in q(a.db, f"select json_object('n', concat('pa_', attribute_name), 'l', attribute_label) from {p}woocommerce_attribute_taxonomies")}

    products = []
    for prod in q(a.db, f"select json_object('id', ID, 'slug', post_name, 'name', post_title, 'content', post_content, 'excerpt', post_excerpt, 'menu', menu_order) from {p}posts where post_type = 'product' and post_status = 'publish' order by menu_order, ID"):
        m = meta(prod["id"])
        attrs = []
        for key, at in (unserialize(m.get("_product_attributes", "")) or {}).items():
            if at.get("is_variation"):
                attrs.append({"name": key, "label": labels.get(key, key), "options": []})
        variations = []
        for v in q(a.db, f"select json_object('id', ID, 'menu', menu_order) from {p}posts where post_type = 'product_variation' and post_status = 'publish' and post_parent = {prod['id']} order by menu_order, ID"):
            vm = meta(v["id"])
            va = {at["name"]: vm.get("attribute_" + at["name"], "") for at in attrs}
            variations.append({"id": v["id"], "sku": vm.get("_sku", ""), "price": round(float(vm.get("_price") or m.get("_price") or 0) * 100), "attributes": va, "image": image(vm.get("_thumbnail_id"))})
        for at in attrs:
            seen = []
            for v in variations:
                s = v["attributes"][at["name"]]
                if s and s not in seen: seen.append(s)
            at["options"] = [{"slug": s, "label": terms.get((at["name"], s), s)} for s in seen]
        gallery = [image(i) for i in (m.get("_product_image_gallery") or "").split(",") if i.strip()]
        products.append({
            "id": prod["id"], "slug": prod["slug"], "name": prod["name"], "site": a.site,
            "price": round(float(m.get("_price") or 0) * 100), "currency": "usd",
            "shipping": m.get("_virtual", "no") != "yes" and m.get("_downloadable", "no") != "yes",
            "image": image(m.get("_thumbnail_id")), "gallery": [g for g in gallery if g],
            "short_description": prod["excerpt"], "description": prod["content"],
            "attributes": attrs, "variations": variations,
        })
    print("/* Generated by scripts/gen-shop-catalog.py from the old WooCommerce shop. Do not edit. */")
    print('import type { Product } from "./catalog";')
    print("export const PRODUCTS: Product[] = " + json.dumps(products, ensure_ascii=False, indent=1) + ";")


if __name__ == "__main__":
    main()
